# Calculadora IMC 

# IMC = peso (kg) / (altura (m)) ** 2
peso = float(input("Tu peso (kg): "))
altura = float(input("Tu altura (m) : " ))
# Definir el IMC
imc = peso / (altura ** 2)
#imprime IMC del usuario
print("Tu IMC es de", imc)


